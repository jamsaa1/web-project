CREATE TABLE public.users_db (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_role VARCHAR(20) NOT NULL DEFAULT 'user' CHECK (user_role IN ('user','admin')),
    user_isactive BOOLEAN NOT NULL DEFAULT TRUE,
    user_name VARCHAR(50) NOT NULL UNIQUE,
    user_email VARCHAR(255) NOT NULL UNIQUE,
    user_registrationdate TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_passwordhash VARCHAR(255) NOT NULL,
    user_privacy VARCHAR(20) NOT NULL DEFAULT 'public' CHECK (user_privacy IN ('public','private'))
);

CREATE TABLE public.logins_db (
    login_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES public.users_db(user_id),
    login_status VARCHAR(20) NOT NULL CHECK (login_status IN ('success','failed')),
    login_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    login_device VARCHAR(255)
);

CREATE TABLE public.movies_db (
    movie_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id INTEGER NOT NULL UNIQUE,
    movie_name VARCHAR(255) NOT NULL,
    movie_year INTEGER
);

CREATE TABLE public.ratings_db (
    rating_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users_db(user_id),
    movie_id INTEGER NOT NULL REFERENCES public.movies_db(movie_id),
    rating_starsnumber DECIMAL(3,1) NOT NULL CHECK (rating_starsnumber BETWEEN 0 AND 10),
    rating_visibility VARCHAR(20) NOT NULL DEFAULT 'public' CHECK (rating_visibility IN ('public','private')),
    UNIQUE (user_id, movie_id)
);

CREATE TABLE public.likedmovie_db (
    likedmovie_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users_db(user_id),
    movie_id INTEGER NOT NULL REFERENCES public.movies_db(movie_id),
    likedmovie_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, movie_id)
);

CREATE TABLE public.groups_db (
    group_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name VARCHAR(100) NOT NULL,
    group_description TEXT,
    group_visibility VARCHAR(20) NOT NULL DEFAULT 'private' CHECK (group_visibility IN ('public','private')),
    group_createdby INTEGER NOT NULL REFERENCES public.users_db(user_id),
    group_createddate TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.groupmembers_db (
    groupmember_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INTEGER NOT NULL REFERENCES public.groups_db(group_id),
    user_id INTEGER NOT NULL REFERENCES public.users_db(user_id),
    member_role VARCHAR(20) NOT NULL DEFAULT 'member' CHECK (member_role IN ('admin','member')),
    joined_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (group_id, user_id)
);

CREATE TABLE public.lists_db (
    list_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_type VARCHAR(20) NOT NULL CHECK (list_type IN ('individual','group')),
    owner_user_id INTEGER REFERENCES public.users_db(user_id),
    owner_group_id INTEGER REFERENCES public.groups_db(group_id),
    list_name VARCHAR(100) NOT NULL,
    list_visibility VARCHAR(20) NOT NULL DEFAULT 'private' CHECK (list_visibility IN ('private','group','link')),
    list_createddate TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((list_type = 'individual' AND owner_user_id IS NOT NULL AND owner_group_id IS NULL) OR (list_type = 'group' AND owner_group_id IS NOT NULL AND owner_user_id IS NULL))
);

CREATE TABLE public.listmovies_db (
    listmovie_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id INTEGER NOT NULL REFERENCES public.lists_db(list_id),
    movie_id INTEGER NOT NULL REFERENCES public.movies_db(movie_id),
    added_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (list_id, movie_id)
);

CREATE TABLE public.genre_db (
    genre_id INTEGER PRIMARY KEY,
    genre_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE public.moviegenres_db (
    movie_id INTEGER REFERENCES public.movies_db(movie_id),
    genre_id INTEGER REFERENCES public.genre_db(genre_id),
    PRIMARY KEY (movie_id, genre_id)
);

CREATE TABLE public.comments_db (
    comment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users_db(user_id),
    movie_id INTEGER NOT NULL REFERENCES public.movies_db(movie_id),
    comment_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    comment_longtext TEXT NOT NULL,
    comment_visibility VARCHAR(20) NOT NULL DEFAULT 'public' CHECK (comment_visibility IN ('public','private'))
);

CREATE TABLE public.groupinvitations_db (
    invitation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INTEGER NOT NULL REFERENCES public.groups_db(group_id),
    invited_user_id INTEGER NOT NULL REFERENCES public.users_db(user_id),
    invited_by INTEGER NOT NULL REFERENCES public.users_db(user_id),
    invitation_status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (invitation_status IN ('pending','accepted','declined','expired')),
    invitation_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.groupvotes_db (
    vote_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INTEGER NOT NULL REFERENCES public.groups_db(group_id),
    movie_id INTEGER NOT NULL REFERENCES public.movies_db(movie_id),
    user_id INTEGER NOT NULL REFERENCES public.users_db(user_id),
    vote_value INTEGER NOT NULL,
    vote_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.groupmessages_db (
    message_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INTEGER NOT NULL REFERENCES public.groups_db(group_id),
    user_id INTEGER NOT NULL REFERENCES public.users_db(user_id),
    message_text TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.userfollows_db (
    follower_id INTEGER REFERENCES public.users_db(user_id),
    following_id INTEGER REFERENCES public.users_db(user_id),
    followed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (follower_id, following_id),
    CHECK (follower_id <> following_id)
);

CREATE TABLE public.userfriendships_db (
    friendship_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users_db(user_id),
    friend_id INTEGER NOT NULL REFERENCES public.users_db(user_id),
    friendship_status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (friendship_status IN ('pending','accepted','rejected')),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (user_id <> friend_id)
);

CREATE TABLE public.movieevents_db (
    event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id INTEGER NOT NULL REFERENCES public.groups_db(group_id),
    created_by INTEGER NOT NULL REFERENCES public.users_db(user_id),
    event_title VARCHAR(150) NOT NULL,
    event_description TEXT,
    event_date TIMESTAMPTZ NOT NULL,
    movie_id INTEGER REFERENCES public.movies_db(movie_id)
);

CREATE TABLE public.eventattendees_db (
    event_id INTEGER REFERENCES public.movieevents_db(event_id),
    user_id INTEGER REFERENCES public.users_db(user_id),
    rsvp_status VARCHAR(20) NOT NULL DEFAULT 'going' CHECK (rsvp_status IN ('going','maybe','not_going')),
    rsvp_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (event_id, user_id)
);

CREATE TABLE public.userblocks_db (
    blocker_id INTEGER REFERENCES public.users_db(user_id),
    blocked_user_id INTEGER REFERENCES public.users_db(user_id),
    blocked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (blocker_id, blocked_user_id),
    CHECK (blocker_id <> blocked_user_id)
);

CREATE TABLE public.contentreports_db (
    report_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id INTEGER NOT NULL REFERENCES public.users_db(user_id),
    content_type VARCHAR(30) NOT NULL,
    content_id INTEGER NOT NULL,
    reason TEXT NOT NULL,
    report_status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (report_status IN ('pending','reviewed','resolved')),
    reported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

